window.KEU.formatPrice = function (value) {
  return value.toLocaleString("pt-BR", {
    style: "currency",
    currency: "BRL",
  });
};

window.KEU.getProduct = function (slug) {
  return window.KEU.products.find(function (p) {
    return p.slug === slug;
  });
};

window.KEU.getCollection = function (slug) {
  return window.KEU.collections.find(function (c) {
    return c.slug === slug;
  });
};

window.KEU.productsByCollection = function (slug) {
  return window.KEU.products.filter(function (p) {
    return p.collection === slug;
  });
};
